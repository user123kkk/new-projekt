"""Counts evidence per cluster and picks the strongest verbatim quotes.

Usage: python -I tools/nachfrage/cluster_stats.py
Input:  quellen/nachfrage/clusters.json, quellen/nachfrage/demand.jsonl
Output: quellen/nachfrage/cluster_stats.md
"""
import json
from collections import Counter
from pathlib import Path

N = Path(__file__).resolve().parents[2] / "quellen" / "nachfrage"


def main():
    rec = {r["id"]: r for r in (json.loads(l) for l in (N / "demand.jsonl").read_text(encoding="utf-8").split("\n") if l.strip())}
    clusters = json.loads((N / "clusters.json").read_text(encoding="utf-8"))
    rows, parts = [], []
    for c in clusters:
        rs = [rec[i] for i in c["ids"]]
        pay = sum(r["pay"] == "explicit" for r in rs)
        pain3 = sum(r["pain"] == 3 for r in rs)
        src = Counter(r["src"] for r in rs)
        # Strength = explicit willingness to pay and stated cost weigh more than a plain wish.
        strength = len(rs) + 3 * pay + 3 * pain3
        rows.append((strength, c, rs, pay, pain3, src))
    rows.sort(key=lambda x: -x[0])
    out = ["# Cluster statistics", "",
           "Strength = posts + 3 × explicit pay + 3 × pain 3. Generated by tools/nachfrage/cluster_stats.py.", "",
           "| # | Cluster | Group | Posts | Pay explicit | Pain 3 | HN / Reddit | Strength |",
           "|---|---|---|---|---|---|---|---|"]
    for n, (s, c, rs, pay, pain3, src) in enumerate(rows, 1):
        out.append(f"| {n} | {c['cluster']} | {c['group']} | {len(rs)} | {pay} | {pain3} | {src['hn']} / {src['reddit']} | {s} |")
    for n, (s, c, rs, pay, pain3, src) in enumerate(rows, 1):
        out += ["", f"## {n}. {c['cluster']}", "", c["description"], ""]
        tools = Counter(t for r in rs for t in r["tools"])
        if tools:
            out.append("Tools named: " + ", ".join(f"{t} ({k})" for t, k in tools.most_common(8)))
            out.append("")
        best = sorted(rs, key=lambda r: (r["pay"] != "explicit", -r["pain"], -(r["score"] or 0)))[:6]
        for r in best:
            out.append(f"- \"{r['quote']}\" ({r['who']}; pain {r['pain']}; pay {r['pay']}; score {r['score']}) {r['url']}")
    (N / "cluster_stats.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[6:36]))


if __name__ == "__main__":
    main()
